def train_optimizer(
    optimizer_name, learning_rate, batch_size=32
):

    torch.manual_seed(SEED)

    model = nn.Linear(8, 1).to(device)

    if optimizer_name == "SGD":
        optimizer = optim.SGD(
            model.parameters(), lr=learning_rate
        )

    elif optimizer_name == "Momentum":
        optimizer = optim.SGD(
            model.parameters(),
            lr=learning_rate,
            momentum=0.9
        )

    elif optimizer_name == "RMSProp":
        optimizer = optim.RMSprop(
            model.parameters(), lr=learning_rate
        )

    else:
        optimizer = optim.Adam(
            model.parameters(), lr=learning_rate
        )

    criterion = nn.MSELoss()

    dataset = TensorDataset(
        X4_train_t, y4_train_t
    )

    loader = DataLoader(
        dataset, batch_size=batch_size, shuffle=True
    )

    history = []

    for epoch in range(50):

        model.train()

        for xb, yb in loader:

            xb = xb.to(device)
            yb = yb.to(device)

            optimizer.zero_grad()

            prediction = model(xb)
            loss = criterion(prediction, yb)

            loss.backward()
            optimizer.step()

        model.eval()

        with torch.no_grad():

            prediction = model(
                X4_val_t.to(device)
            )

            val_loss = criterion(
                prediction, y4_val_t.to(device)
            ).item()

        history.append(val_loss)

    rmse = np.sqrt(history[-1])

    return rmse, history


