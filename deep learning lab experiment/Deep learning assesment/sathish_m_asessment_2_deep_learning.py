class WildlifeCNN(nn.Module):

    def __init__(self, channels, image_size):

        super().__init__()

        layers = []
        in_channels = 3

        for out_channels in channels:

            layers.extend([
                nn.Conv2d(
                    in_channels,
                    out_channels,
                    kernel_size=3,
                    padding=1
                ),
                nn.ReLU(),
                nn.MaxPool2d(2)
            ])

            in_channels = out_channels

        self.features = nn.Sequential(*layers)

        final_size = image_size // (2 ** len(channels))

        self.classifier = nn.Linear(
            in_channels * final_size * final_size,
            4
        )

    def forward(self, x):

        x = self.features(x)
        x = torch.flatten(x, 1)

        return self.classifier(x)


