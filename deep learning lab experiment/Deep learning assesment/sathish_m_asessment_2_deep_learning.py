def sigmoid(x):
    return 1 / (1 + np.exp(-np.clip(x, -500, 500)))


def forward_numpy(X, W1, b1, W2, b2):

    Z1 = X @ W1 + b1
    A1 = sigmoid(Z1)

    Z2 = A1 @ W2 + b2
    A2 = sigmoid(Z2)

    return A1, A2


def binary_loss(y, prediction):

    prediction = np.clip(prediction, 1e-12, 1 - 1e-12)

    return -np.mean(
        y * np.log(prediction)
        + (1-y) * np.log(1-prediction)
    )


def backward_numpy(X, y, W1, b1, W2, b2, bug=False):

    m = X.shape[0]

    A1, A2 = forward_numpy(X, W1, b1, W2, b2)

    dZ2 = (A2-y) / m
    dW2 = A1.T @ dZ2
    db2 = np.sum(dZ2, axis=0, keepdims=True)

    dA1 = dZ2 @ W2.T

    if bug:
        dZ1 = dA1
    else:
        dZ1 = dA1 * A1 * (1-A1)

    dW1 = X.T @ dZ1
    db1 = np.sum(dZ1, axis=0, keepdims=True)

    return {
        "W1": dW1,
        "b1": db1,
        "W2": dW2,
        "b2": db2
    }


def numerical_gradient(parameter_name, parameters, epsilon):

    parameter = parameters[parameter_name]
    numerical = np.zeros_like(parameter)

    for index in np.ndindex(parameter.shape):

        plus = {k: v.copy() for k, v in parameters.items()}
        minus = {k: v.copy() for k, v in parameters.items()}

        plus[parameter_name][index] += epsilon
        minus[parameter_name][index] -= epsilon

        loss_plus = binary_loss(
            y2,
            forward_numpy(
                X2, plus["W1"], plus["b1"],
                plus["W2"], plus["b2"]
            )[1]
        )

        loss_minus = binary_loss(
            y2,
            forward_numpy(
                X2, minus["W1"], minus["b1"],
                minus["W2"], minus["b2"]
            )[1]
        )

        numerical[index] = (
            loss_plus-loss_minus
        ) / (2*epsilon)

    return numerical


def relative_error(a, b):

    return np.linalg.norm(a-b) / (
        np.linalg.norm(a) + np.linalg.norm(b) + 1e-15
    )


