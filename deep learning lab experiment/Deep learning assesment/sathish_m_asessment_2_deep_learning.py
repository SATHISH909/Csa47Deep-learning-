class RegularizationNetwork(nn.Module):

    def __init__(self, hidden=64):
        super().__init__()

        self.layers = nn.Sequential(
            nn.Linear(24, hidden),
            nn.ReLU(),
            nn.Linear(hidden, hidden),
            nn.ReLU(),
            nn.Linear(hidden, 1)
        )

    def forward(self, x):
        return self.layers(x)


def run_regularization(
    Xtr, ytr, Xval, yval,
    l2=0.0, early_stopping=False,
    epochs=80, hidden=64
):

    torch.manual_seed(SEED)

    model = RegularizationNetwork(hidden).to(device)

    optimizer = optim.Adam(
        model.parameters(),
        lr=0.005,
        weight_decay=l2
    )

    criterion = nn.BCEWithLogitsLoss()

    Xtr_t = torch.tensor(
        Xtr, dtype=torch.float32
    ).to(device)

    ytr_t = torch.tensor(
        ytr, dtype=torch.float32
    ).reshape(-1, 1).to(device)

    Xval_t = torch.tensor(
        Xval, dtype=torch.float32
    ).to(device)

    yval_t = torch.tensor(
        yval, dtype=torch.float32
    ).reshape(-1, 1).to(device)

    best_loss = float("inf")
    best_state = copy.deepcopy(model.state_dict())
    wait = 0
    patience = 10

    history = {"train_loss": [], "val_loss": []}

    for epoch in range(epochs):

        model.train()

        optimizer.zero_grad()

        output = model(Xtr_t)
        loss = criterion(output, ytr_t)

        loss.backward()
        optimizer.step()

        model.eval()

        with torch.no_grad():

            val_output = model(Xval_t)
            val_loss = criterion(val_output, yval_t).item()

        history["train_loss"].append(loss.item())
        history["val_loss"].append(val_loss)

        if val_loss < best_loss:

            best_loss = val_loss
            best_state = copy.deepcopy(model.state_dict())
            wait = 0

        else:
            wait += 1

        if early_stopping and wait >= patience:
            break

    model.load_state_dict(best_state)
    model.eval()

    with torch.no_grad():

        train_pred = (
            torch.sigmoid(model(Xtr_t)) >= 0.5
        ).cpu().numpy().flatten()

        val_pred = (
            torch.sigmoid(model(Xval_t)) >= 0.5
        ).cpu().numpy().flatten()

    train_acc = accuracy_score(ytr, train_pred)
    val_acc = accuracy_score(yval, val_pred)

    return {
        "Train Accuracy": train_acc,
        "Validation Accuracy": val_acc,
        "Gap": train_acc-val_acc,
        "Epochs": len(history["train_loss"]),
        "History": history,
        "Model": model
    }


